import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { decode } from '@vcpu/cpu-core';
import {
  FaultCode,
  INSTRUCTION_FORMATS,
  MEMORY_SIZE,
  OPCODES,
  type OpcodeInfo,
} from '@vcpu/shared';
import { condCode, flagMask, ISA_CTRL, ISA_FIELDS } from './isa-pkg.js';

/** File names written by `writeDecoderVectors()`, read by tb/unit/tb_vcpu8_decoder.sv. */
export const DECODER_OPS_FILE = 'decoder-ops.hex';
export const DECODER_RB_FILE = 'decoder-rb.hex';

const OPCODE_SPACE = 256;
const REGISTER_BYTE_SPACE = 256;

const FIELDS_CODE = [ISA_FIELDS.NONE, ISA_FIELDS.A, ISA_FIELDS.AB] as const;
const CTRL_CODE = {
  sequential: ISA_CTRL.SEQ,
  halt: ISA_CTRL.HALT,
  jump: ISA_CTRL.JUMP,
  branch: ISA_CTRL.BRANCH,
  call: ISA_CTRL.CALL,
  return: ISA_CTRL.RET,
} as const satisfies Record<OpcodeInfo['controlFlow'], number>;

/**
 * What the TypeScript ISA says about one opcode byte, in the codes of `vcpu8_isa_pkg.sv`. Every
 * field is 0 for a byte that is not an opcode, which is also what the decoder must drive.
 */
export interface DecoderOpRecord {
  readonly opcode: number;
  readonly valid: 0 | 1;
  /** Instruction length in bytes; 0 when invalid. */
  readonly len: number;
  /** `ISA_FIELDS` code. */
  readonly fields: number;
  /** FLAGS bits written or cleared, bit 3 = Z … bit 0 = V. */
  readonly flagMask: number;
  /** `ISA_CTRL` code. */
  readonly ctrl: number;
  /** `{flag bit index, value}`; 0 unless a branch. */
  readonly cond: number;
  readonly dataRead: 0 | 1;
  readonly dataWrite: 0 | 1;
  /** 1 when an operand has role `dest`: the instruction writes a register. */
  readonly writesReg: 0 | 1;
}

/** Whether cpu-core's `decode()` faults one (opcode, register byte) pair with MALFORMED_OPERAND. */
export interface DecoderRbRecord {
  readonly opcode: number;
  readonly rb: number;
  readonly malformed: 0 | 1;
}

const bit = (value: boolean): 0 | 1 => (value ? 1 : 0);

/** One record per opcode byte 0x00–0xFF, derived from `OPCODES`. */
export function decoderOpRecords(): DecoderOpRecord[] {
  const byOpcode = new Map(OPCODES.map((info) => [info.opcode, info]));
  return Array.from({ length: OPCODE_SPACE }, (_, opcode): DecoderOpRecord => {
    const info = byOpcode.get(opcode);
    if (info === undefined) {
      return {
        opcode,
        valid: 0,
        len: 0,
        fields: ISA_FIELDS.NONE,
        flagMask: 0,
        ctrl: ISA_CTRL.SEQ,
        cond: 0,
        dataRead: 0,
        dataWrite: 0,
        writesReg: 0,
      };
    }
    return {
      opcode,
      valid: 1,
      len: info.length,
      fields: FIELDS_CODE[INSTRUCTION_FORMATS[info.format].registerFields],
      flagMask: flagMask(info),
      ctrl: CTRL_CODE[info.controlFlow],
      cond: condCode(info),
      dataRead: info.dataReads,
      dataWrite: info.dataWrites,
      writesReg: bit(info.operands.some((operand) => operand.role === 'dest')),
    };
  });
}

/**
 * One record per (opcode, register byte) pair, opcode-major. Each pair is decoded by cpu-core
 * from `[opcode, rb, 0x00]` at address 0 of a zeroed memory, so no instruction overruns, and
 * `malformed` is 1 exactly when the result is MALFORMED_OPERAND: an invalid opcode, or a format
 * without a register byte, gives 0.
 */
export function decoderRbRecords(): DecoderRbRecord[] {
  const memory = new Uint8Array(MEMORY_SIZE);
  const records: DecoderRbRecord[] = [];
  for (let opcode = 0; opcode < OPCODE_SPACE; opcode += 1) {
    for (let rb = 0; rb < REGISTER_BYTE_SPACE; rb += 1) {
      memory[0] = opcode;
      memory[1] = rb;
      const result = decode(memory, 0);
      records.push({
        opcode,
        rb,
        malformed: bit(!result.ok && result.fault.code === FaultCode.MALFORMED_OPERAND),
      });
    }
  }
  return records;
}

const hex = (value: number, digits: number): string =>
  value.toString(16).toUpperCase().padStart(digits, '0');

/**
 * `$readmemh` text: one 44-bit word per opcode, one hex digit per field after the opcode byte, so
 * a line reads as its fields (`24 1 2 1 B 0 0 0 0 1` for INC, without the spaces).
 */
export function renderDecoderOps(records: readonly DecoderOpRecord[]): string {
  const lines = [
    '// GENERATED by @vcpu/rtl-tools (packages/rtl-tools/src/gen/decoder-vectors.ts) from @vcpu/shared.',
    `// ${String(records.length)} records, one per opcode byte in order. Hex digits:`,
    '// [43:36] opcode, [35:32] valid, [31:28] len, [27:24] fields, [23:20] flag_mask (ZCNV),',
    '// [19:16] ctrl, [15:12] cond, [11:8] data_read, [7:4] data_write, [3:0] writes_reg.',
  ];
  for (const r of records) {
    lines.push(
      hex(r.opcode, 2) +
        [r.valid, r.len, r.fields, r.flagMask, r.ctrl, r.cond, r.dataRead, r.dataWrite, r.writesReg]
          .map((field) => hex(field, 1))
          .join(''),
    );
  }
  return `${lines.join('\n')}\n`;
}

/** `$readmemh` text: one 20-bit word per pair, `{opcode, rb, malformed}`. */
export function renderDecoderRb(records: readonly DecoderRbRecord[]): string {
  const lines = [
    '// GENERATED by @vcpu/rtl-tools (packages/rtl-tools/src/gen/decoder-vectors.ts) from cpu-core decode().',
    `// ${String(records.length)} records, opcode-major. Hex digits: [19:12] opcode, [11:4] rb,`,
    '// [3:0] malformed (1 when decode() reports MALFORMED_OPERAND).',
  ];
  for (const r of records) {
    lines.push(hex(r.opcode, 2) + hex(r.rb, 2) + hex(r.malformed, 1));
  }
  return `${lines.join('\n')}\n`;
}

/** Writes both vector files into `outDir` and returns their paths. */
export function writeDecoderVectors(outDir: string): string[] {
  mkdirSync(outDir, { recursive: true });
  const ops = join(outDir, DECODER_OPS_FILE);
  const rb = join(outDir, DECODER_RB_FILE);
  writeFileSync(ops, renderDecoderOps(decoderOpRecords()));
  writeFileSync(rb, renderDecoderRb(decoderRbRecords()));
  return [ops, rb];
}
