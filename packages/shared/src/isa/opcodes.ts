/** 256-entry lookup by opcode byte; `undefined` means INVALID_OPCODE. */
export const opcodeByByte: readonly (OpcodeInfo | undefined)[] = deepFreeze(
  Array.from({ length: 256 }, (_, byte) => OPCODES.find((info) => info.opcode === byte)),
);

/** Opcode variants per mnemonic, in opcode order. LOAD and STORE have two each. */
export const opcodesByMnemonic: Readonly<Record<Mnemonic, readonly OpcodeInfo[]>> = deepFreeze(
  OPCODES.reduce<Partial<Record<Mnemonic, OpcodeInfo[]>>>((byMnemonic, info) => {
    (byMnemonic[info.mnemonic] ??= []).push(info);
    return byMnemonic;
  }, {}) as Record<Mnemonic, OpcodeInfo[]>,
);

/** Opcode table row by opcode id. */
export const opcodeById: Readonly<Record<OpcodeId, OpcodeInfo>> = deepFreeze(
  Object.fromEntries(OPCODES.map((info) => [info.id, info])) as Record<OpcodeId, OpcodeInfo>,
);

/** Looks up an opcode byte; `undefined` for an invalid opcode or a value that is not a byte. */
export function lookupOpcode(byte: number): OpcodeInfo | undefined {
  return opcodeByByte[byte];
}

/** Estimated cycles for one retired instruction under the documented timing model. */
export function estimatedCycles(info: OpcodeInfo, controlTransferred: boolean): number {
  return info.baseCycles + (controlTransferred ? info.branchTakenPenalty : 0);
}
