import { assemble, formatDiagnostic } from '@vcpu/assembler';
import { MEMORY_SIZE } from '@vcpu/shared';
import { type MatmulDims, validateDims } from '../model/matmul.js';

/**
 * The VCPU-8 side of the CPU comparison (`make -C hardware/accelerators/matmul compare-cpu`): a
 * generator of VCPU-8 assembly that computes C = A (M × K) × B (K × N) with signed INT8 operands
 * and signed INT32 results that wrap like the reference model's. The ISA is unchanged, so the
 * program builds what the accelerator does in hardware out of 8-bit instructions:
 *
 * - **Multiply.** `MUL` keeps only the low byte of an unsigned product, so the signed 8 × 8 →
 *   16-bit product is computed by shift-and-add instead: the multiplicand is a sign-extended
 *   to 16 bits, the multiplier b is taken as its unsigned bits u (u = b, or b + 256 when b < 0),
 *   and every set bit of u adds the multiplicand shifted to that bit. That sum is a · u mod 2^16,
 *   so when b < 0 the program subtracts 256 · a (a from the high byte), which leaves a · b. Every
 *   INT8 product lies in −16 256 … 16 384, so the 16-bit result is exact. The loop stops as soon
 *   as no multiplier bit is left, so it runs once per bit up to b's highest set bit (8 times for
 *   any negative b): the CPU's cycles depend on the data, the accelerator's do not.
 * - **Accumulate.** C[i][j] is 4 bytes, little-endian, in memory. The product is sign-extended to
 *   32 bits and added byte by byte; there is no add-with-carry, so the carry of each `ADD` is kept
 *   in the C flag (LOAD, STORE, MOV, INC and DEC leave C alone) and added into the next addend
 *   byte with `INC` before its `ADD`. When that `INC` wraps (an addend byte of 0xFF plus a carry)
 *   the byte is unchanged and the carry continues. This is a full INT32 add, so C wraps exactly
 *   like the reference's `| 0`.
 * - **Loops.** The k, j and i loops run on registers and compare addresses with labels, so the code
 *   is the same size for every workload: only the data grows. {@link generateCpuProgram} refuses a
 *   workload whose code, data and stack do not fit in the 256 bytes of memory.
 *
 * Memory map (from address 0): the code, then `cptr` (the address of the C element being
 * accumulated, initialised by the image), A (M · K bytes, row-major), B (K · N bytes, row-major)
 * and C (4 · M · N bytes, zero in the image). The one `PUSH` (R3 around the accumulate loop) uses
 * the top byte, 0xFF, so the image must end at 0xFE. The image is a one-shot program: C starts
 * at zero because the image holds zeros, and running it again without reloading would add twice.
 */

/** Bytes of the stack the program uses: one `PUSH R3` deep. */
export const CPU_STACK_BYTES = 1;

/** Data bytes of a workload: the `cptr` variable, A, B and C (4 bytes per element). */
export function cpuDataBytes(dims: MatmulDims): number {
  const { m, n, k } = dims;
  return 1 + m * k + k * n + 4 * m * n;
}

/** Where each part of a program sits in memory. */
export interface CpuProgramLayout {
  /** Code occupies [0, codeBytes). */
  readonly codeBytes: number;
  readonly cptr: number;
  readonly a: number;
  readonly b: number;
  readonly c: number;
  /** One past the last image byte. */
  readonly end: number;
}

export interface CpuProgram {
  readonly dims: MatmulDims;
  /** The generated assembly. */
  readonly source: string;
  /** All 256 bytes of memory as the program starts. */
  readonly image: Uint8Array;
  readonly layout: CpuProgramLayout;
  readonly dataBytes: number;
  /** codeBytes + dataBytes + {@link CPU_STACK_BYTES}. */
  readonly totalBytes: number;
}

/** A workload the CPU can run, or why it cannot. */
export type CpuProgramResult =
  | { readonly ok: true; readonly program: CpuProgram }
  | {
      readonly ok: false;
      readonly dims: MatmulDims;
      readonly codeBytes: number;
      readonly dataBytes: number;
      readonly stackBytes: number;
      readonly totalBytes: number;
      readonly reason: string;
    };

function byteLines(label: string, values: readonly number[], perLine: number): string[] {
  const lines: string[] = [`${label}:`];
  for (let i = 0; i < values.length; i += perLine) {
    lines.push(`        .byte ${values.slice(i, i + perLine).join(', ')}`);
  }
  return lines;
}

/** The code, the same for every operand value; the immediates depend only on the dimensions. */
function codeLines(dims: MatmulDims): string[] {
  const { m, n, k } = dims;
  // The immediates must assemble even for a workload that does not fit, whose size is only
  // being measured; the code length does not depend on their values.
  const imm = (value: number) => String(value & 0xff);
  return [
    `; C = A (${String(m)} x ${String(k)}) x B (${String(k)} x ${String(n)}), signed INT8 -> INT32 (wraps)`,
    '; generated by packages/accelerator-reference/src/harness/cpu-program.ts; do not edit',
    ';',
    '; R1 = &A[i][k], R2 = &B[k][j], R3 = k left; R4..R7 and R0 do the multiply and accumulate.',
    '; C[i][j] is 4 bytes little-endian; cptr holds the address of the one being accumulated.',
    `        .equ K, ${imm(k)}`,
    `        .equ N, ${imm(n)}`,
    `        .equ KN_1, ${imm(k * n - 1)}          ; K * N - 1: from &B[K][j] back to &B[0][j + 1]`,
    '        LDI R1, a',
    '        LDI R2, b',
    'col:    LDI R3, K',
    '; ---- R0:R7 = A[i][k] * B[k][j], signed 8 x 8 -> 16 bits, by shift-and-add ----',
    'mac:    LOAD R4, [R1]       ; R5:R4 = the multiplicand a, sign-extended below',
    '        LOAD R6, [R2]       ; R6 = the multiplier b, taken as unsigned bits u',
    '        XOR R0, R0          ; R0 = product high byte = 0',
    '        MOV R5, R4',
    '        SHL R5              ; C = sign of a',
    '        MOV R5, R0          ; MOV keeps the flags',
    '        MOV R7, R0          ; R7 = product low byte = 0',
    '        JNC mul_bit',
    '        DEC R5              ; a < 0: R5 = 0xFF',
    'mul_bit: SHR R6             ; C = the next bit of u',
    '        JNC mul_shift',
    '        ADD R7, R4          ; R0:R7 += R5:R4',
    '        JNC mul_hi',
    '        INC R0',
    'mul_hi: ADD R0, R5',
    'mul_shift:',
    '        SHL R5              ; R5:R4 <<= 1',
    '        SHL R4',
    '        JNC mul_next',
    '        INC R5',
    'mul_next:',
    '        OR R6, R6',
    '        JNZ mul_bit         ; until no bit of u is left',
    '        LOAD R5, [R2]',
    '        SHL R5              ; C = sign of b',
    '        JNC acc_ext',
    '        LOAD R4, [R1]',
    '        SUB R0, R4          ; b < 0: u = b + 256, so take 256 * a back off',
    '; ---- C[i][j] += the product sign-extended to 32 bits, carry kept in C ----',
    'acc_ext:',
    '        MOV R4, R0',
    '        SHL R4              ; C = sign of the product',
    '        JNC acc_init',
    '        DEC R6              ; R6 = extension byte: 0 (the loop left R6 = 0) or 0xFF',
    'acc_init:',
    '        PUSH R3',
    '        LDI R3, 4',
    '        LOAD R5, [cptr]     ; R5 = &C[i][j]',
    '        AND R4, R4          ; C = 0: no carry into byte 0',
    'acc:    LOAD R4, [R5]',
    '        JNC acc_add',
    '        INC R7              ; carry in: addend byte + 1 ...',
    '        JZ acc_store        ; ... 0xFF + 1 wrapped: the byte stays, C stays 1',
    'acc_add:',
    '        ADD R4, R7',
    'acc_store:',
    '        STORE [R5], R4',
    '        INC R5',
    '        MOV R7, R0          ; next addend byte: product high byte, then the extension',
    '        MOV R0, R6',
    '        DEC R3',
    '        JNZ acc',
    '        POP R3',
    '; ---- next k ----',
    '        INC R1',
    '        LDI R4, N',
    '        ADD R2, R4',
    '        DEC R3',
    '        JNZ mac',
    '; ---- next C element: R5 = &C[i][j] + 4 ----',
    '        STORE [cptr], R5',
    '        LDI R4, KN_1',
    '        SUB R2, R4          ; R2 = &B[0][j + 1]',
    '        LDI R4, b_row1',
    '        CMP R2, R4',
    '        JZ row              ; j + 1 = N',
    '        LDI R4, K',
    '        SUB R1, R4          ; R1 = &A[i][0] again',
    '        JMP col',
    'row:    LDI R2, b           ; R1 is &A[i + 1][0] already',
    '        LDI R4, a_end',
    '        CMP R1, R4',
    '        JNZ col             ; i + 1 < M',
    '        HLT',
  ];
}

function dataLines(
  dims: MatmulDims,
  a: ArrayLike<number>,
  b: ArrayLike<number>,
): string[] {
  const { m, n, k } = dims;
  const values = (array: ArrayLike<number>, length: number) =>
    Array.from({ length }, (_, i) => array[i] ?? 0);
  const av = values(a, m * k);
  const bv = values(b, k * n);
  return [
    'cptr:   .byte c',
    ...byteLines('a', av, k),
    'a_end:',
    ...byteLines('b', bv.slice(0, n), n),
    ...byteLines('b_row1', bv.slice(n), n),
    ...byteLines('c', new Array<number>(4 * m * n).fill(0), 16),
  ];
}

function assembleOrThrow(source: string) {
  const result = assemble(source);
  if (!result.ok) {
    const errors = result.diagnostics
      .filter((d) => d.severity === 'error')
      .map((d) => formatDiagnostic(d, source));
    throw new Error(`the generated VCPU-8 program does not assemble:\n${errors.join('\n')}`);
  }
  return result;
}

/** The code length of the program for `dims`, which does not depend on the operand values. */
export function cpuCodeBytes(dims: MatmulDims): number {
  // Every label the code refers to, defined without any data after it.
  const source = [...codeLines(dims), 'cptr:', 'a:', 'a_end:', 'b:', 'b_row1:', 'c:', ''].join(
    '\n',
  );
  const symbol = assembleOrThrow(source).symbols.get('cptr');
  if (symbol === undefined) throw new Error('the generated program has no cptr label');
  return symbol.value;
}

/**
 * The program for C = A × B (A row-major M × K, B row-major K × N, signed INT8), or, when code,
 * data and stack do not fit in memory, the byte counts that did not fit.
 */
export function generateCpuProgram(
  dims: MatmulDims,
  a: ArrayLike<number>,
  b: ArrayLike<number>,
): CpuProgramResult {
  validateDims(dims);
  const codeBytes = cpuCodeBytes(dims);
  const dataBytes = cpuDataBytes(dims);
  const totalBytes = codeBytes + dataBytes + CPU_STACK_BYTES;
  if (totalBytes > MEMORY_SIZE) {
    return {
      ok: false,
      dims,
      codeBytes,
      dataBytes,
      stackBytes: CPU_STACK_BYTES,
      totalBytes,
      reason: `needs ${String(totalBytes)} bytes (code ${String(codeBytes)} + data ${String(dataBytes)} + stack ${String(CPU_STACK_BYTES)}), more than the ${String(MEMORY_SIZE)} bytes of VCPU-8 memory`,
    };
  }
  for (const [name, matrix, length] of [
    ['A', a, dims.m * dims.k],
    ['B', b, dims.k * dims.n],
  ] as const) {
    if (matrix.length !== length) {
      throw new RangeError(`${name} has ${String(matrix.length)} values, expected ${String(length)}`);
    }
    for (let i = 0; i < length; i += 1) {
      const value = matrix[i] ?? 0;
      if (!Number.isInteger(value) || value < -128 || value > 127) {
        throw new RangeError(`${name}[${String(i)}] = ${String(value)} is not a signed INT8`);
      }
    }
  }
  const source = `${[...codeLines(dims), ...dataLines(dims, a, b)].join('\n')}\n`;
  const result = assembleOrThrow(source);
  const at = (name: string) => {
    const symbol = result.symbols.get(name);
    if (symbol === undefined) throw new Error(`the generated program has no ${name} label`);
    return symbol.value;
  };
  // Address ranges are inclusive.
  const last = result.bytes.ranges.at(-1);
  const end = last === undefined ? 0 : last.end + 1;
  const layout: CpuProgramLayout = {
    codeBytes,
    cptr: at('cptr'),
    a: at('a'),
    b: at('b'),
    c: at('c'),
    end,
  };
  if (end + CPU_STACK_BYTES > MEMORY_SIZE || end !== codeBytes + dataBytes) {
    throw new Error(
      `the generated program ends at ${String(end)}, expected ${String(codeBytes + dataBytes)}`,
    );
  }
  return {
    ok: true,
    program: { dims, source, image: result.bytes.image, layout, dataBytes, totalBytes },
  };
}

/** C as the program leaves it in memory: M · N little-endian INT32s from `layout.c`. */
export function readCpuResult(
  memory: ArrayLike<number>,
  program: Pick<CpuProgram, 'dims' | 'layout'>,
): Int32Array {
  const { m, n } = program.dims;
  const c = new Int32Array(m * n);
  for (let e = 0; e < m * n; e += 1) {
    const base = program.layout.c + 4 * e;
    const byte = (i: number) => memory[base + i] ?? 0;
    c[e] = byte(0) | (byte(1) << 8) | (byte(2) << 16) | (byte(3) << 24);
  }
  return c;
}
